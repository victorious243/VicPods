function buildGuidePath(slug) {
  return `/guides/${slug}`;
}

function getSeoGuides() {
  return GUIDES.map((guide) => ({
    ...guide,
    path: buildGuidePath(guide.slug),
  }));
}

function getSeoGuideBySlug(slug) {
  return getSeoGuides().find((guide) => guide.slug === slug) || null;
}

function getSeoGuideIndexPage() {
  return {
    title: 'Podcast Guides and Templates',
    subtitle: 'Search-first resources for podcasters who want clearer planning, stronger episodes, and better launch prep.',
    description: 'Browse podcast guides, templates, and planning resources from VicPods, including how to start a podcast, outline episodes, plan a season, and launch stronger.',
    guides: getSeoGuides(),
  };
}

function getSeoGuidePathLabelMap() {
  const map = {
    '/': 'Home',
    '/podcast-idea-generator': 'Podcast Idea Generator',
    '/examples': 'Example Library',
    '/about': 'About VicPods',
    '/help': 'Help Center',
    '/terms': 'Terms',
    '/privacy-policy': 'Privacy Policy',
    '/cookie-policy': 'Cookie Policy',
    '/data-rights': 'Data Rights',
    '/guides': 'Podcast Guides',
  };

  getSeoGuides().forEach((guide) => {
    map[guide.path] = guide.title;
  });

  return map;
}

function getIndexableGuidePages() {
  return getSeoGuides().map((guide) => ({
    path: guide.path,
    changefreq: 'weekly',
    priority: '0.8',
  }));
}

